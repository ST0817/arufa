use std::fmt::{self, Display, Formatter, Write};

#[derive(Debug, Clone, PartialEq)]
pub enum Token<'src> {
    Plus,
    Minus,
    Star,
    Slash,
    Perc,
    Assign,
    Eq,
    LT,
    LE,
    GT,
    GE,
    Not,
    NotEq,
    Colon,
    Semic,
    Comma,
    LParen,
    RParen,
    LBrace,
    RBrace,
    I32,
    Bool,
    True,
    False,
    If,
    Else,
    Var,
    Int(u32),
    Name(&'src str),
}

impl Display for Token<'_> {
    fn fmt(&self, f: &mut Formatter) -> fmt::Result {
        use Token::*;
        match self {
            Plus => f.write_char('+'),
            Minus => f.write_char('-'),
            Star => f.write_char('*'),
            Slash => f.write_char('/'),
            Perc => f.write_char('%'),
            Assign => f.write_char('='),
            Eq => f.write_str("=="),
            LT => f.write_char('<'),
            LE => f.write_str("<="),
            GT => f.write_char('>'),
            GE => f.write_str(">="),
            Not => f.write_char('!'),
            NotEq => f.write_str("!="),
            Colon => f.write_char(':'),
            Semic => f.write_char(';'),
            Comma => f.write_char(','),
            LParen => f.write_char('('),
            RParen => f.write_char(')'),
            LBrace => f.write_char('{'),
            RBrace => f.write_char('}'),
            I32 => f.write_str("i32"),
            Bool => f.write_str("bool"),
            True => f.write_str("true"),
            False => f.write_str("false"),
            If => f.write_str("if"),
            Else => f.write_str("else"),
            Var => f.write_str("var"),
            Int(value) => write!(f, "{value}"),
            Name(name) => f.write_str(name),
        }
    }
}
