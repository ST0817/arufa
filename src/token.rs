use std::fmt::{self, Display, Formatter, Write};

#[derive(Debug, Clone, PartialEq)]
pub enum Token<'src> {
    Plus,
    Arrow,
    Minus,
    Star,
    Slash,
    Perc,
    Assign,
    Eq,
    LShift,
    LE,
    LT,
    RShift,
    GE,
    GT,
    NotEq,
    Not,
    Amp,
    Pipe,
    Hat,
    Colon,
    Semic,
    Comma,
    LParen,
    RParen,
    LBrace,
    RBrace,
    I32,
    Bool,
    Str,
    True,
    False,
    And,
    Or,
    If,
    Else,
    Var,
    Fn,
    Extern,
    Int(u32),
    String(String),
    Name(&'src str),
}

impl Display for Token<'_> {
    fn fmt(&self, f: &mut Formatter) -> fmt::Result {
        use Token::*;
        match self {
            Plus => f.write_char('+'),
            Arrow => f.write_str("->"),
            Minus => f.write_char('-'),
            Star => f.write_char('*'),
            Slash => f.write_char('/'),
            Perc => f.write_char('%'),
            Eq => f.write_str("=="),
            Assign => f.write_char('='),
            LShift => f.write_str("<<"),
            LE => f.write_str("<="),
            LT => f.write_char('<'),
            RShift => f.write_str(">>"),
            GT => f.write_char('>'),
            GE => f.write_str(">="),
            NotEq => f.write_str("!="),
            Not => f.write_char('!'),
            Amp => f.write_char('&'),
            Pipe => f.write_char('|'),
            Hat => f.write_char('^'),
            Colon => f.write_char(':'),
            Semic => f.write_char(';'),
            Comma => f.write_char(','),
            LParen => f.write_char('('),
            RParen => f.write_char(')'),
            LBrace => f.write_char('{'),
            RBrace => f.write_char('}'),
            I32 => f.write_str("i32"),
            Bool => f.write_str("bool"),
            Str => f.write_str("str"),
            True => f.write_str("true"),
            False => f.write_str("false"),
            And => f.write_str("and"),
            Or => f.write_str("or"),
            If => f.write_str("if"),
            Else => f.write_str("else"),
            Var => f.write_str("var"),
            Fn => f.write_str("fn"),
            Extern => f.write_str("extern"),
            Int(value) => write!(f, "{value}"),
            String(value) => write!(f, r#""{value}""#),
            Name(name) => f.write_str(name),
        }
    }
}
